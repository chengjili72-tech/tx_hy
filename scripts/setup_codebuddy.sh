#!/usr/bin/env bash
# CodeBuddy：共享原生二进制和配置；setup 复用已有二进制，不反复联网安装。
# 首次迁移 ~/.codebuddy：bash setup_codebuddy.sh migrate
# 已迁移/更换容器/全新安装：bash setup_codebuddy.sh setup
# 手动升级共享二进制：bash setup_codebuddy.sh update
# 可覆盖目标：CB_ROOT=/共享路径/codebuddy_cli bash setup_codebuddy.sh setup
# 可覆盖迁移源：CB_MIGRATE_FROM=/旧路径 bash setup_codebuddy.sh migrate
# 官方说明：https://www.codebuddy.cn/docs/cli/installation
# Linux + Bash；用 bash 执行本脚本，不要 source 本脚本。
# 依赖 curl、CA 证书和 GNU coreutils；无需激活 Conda，也不改动训练环境。
# 共享目录需提前挂载且允许执行；不同 CPU 架构不要共用同一份二进制。
# 迁移/升级前退出所有使用该共享目录的 CLI（包括其他容器）。
# 目录含登录信息，请仅供本人使用；不要同时从多台主机写同一份状态数据库。
# 代理沿用当前 shell 的 http_proxy/https_proxy/no_proxy，不写入 bashrc。
# 非交互任务请显式 source 下文生成的 env 文件，不依赖 /etc/profile。
[[ "${BASH_SOURCE[0]}" == "$0" ]] || { echo '请用 bash 执行，不要 source。' >&2; return 1; }
set -euo pipefail
umask 077
mode="${1:-setup}"
case "$mode" in setup|migrate|update) ;; *) echo "用法：bash $0 [setup|migrate|update]" >&2; exit 2;; esac
fail() { echo "错误：$*" >&2; exit 1; }
[[ $(uname -s) == Linux ]] || fail '本脚本用于 Linux 容器。'
# migrate 只允许目标不存在；失败后保留部分副本，人工检查后再处理，绝不自动覆盖。
migrate_data() {
    local src="$1" dst="$2"
    [[ -d "$src" ]] || fail "源目录不存在：$src"
    [[ ! -e "$dst" && ! -L "$dst" ]] || fail "目标已存在，请检查后使用 setup：$dst"
    src=$(realpath -e -- "$src")
    dst=$(realpath -m -- "$dst")
    case "$dst/" in "$src/"*) fail '迁移目标不能位于源目录内。';; esac
    mkdir -p -- "$(dirname -- "$dst")"
    mkdir -m 700 -- "$dst"
    touch "$dst/.tx-hy-migration-incomplete"
    cp -a -- "$src/." "$dst/"
    rm -- "$dst/.tx-hy-migration-incomplete"
    chmod 700 -- "$dst"
}
# 只追加一次入口；后续更新独立 env 文件，避免不断追加 export。
# 若之前已有旧 export，保留原文；本入口放在末尾，以当前配置为准。
write_bashrc_entry() {
    local env_file="$1" line
    printf -v line '[ -r %q ] && source %q # tx_hy-%s-env' "$env_file" "$env_file" "$tool"
    touch "$HOME/.bashrc"
    if ! grep -Fqx -- "$line" "$HOME/.bashrc"; then
        cp -p -- "$HOME/.bashrc" "$HOME/.bashrc.bak.$(date +%Y%m%d%H%M%S).$$"
        printf '\n%s\n' "$line" >> "$HOME/.bashrc"
    fi
}
tmp=''
trap '[[ -z "$tmp" ]] || rm -f -- "$tmp"' EXIT
# 先完整下载再执行，避免下载中断时运行不完整安装脚本。
download_installer() {
    command -v curl >/dev/null || fail '请先安装 curl 和 ca-certificates。'
    tmp=$(mktemp)
    curl --fail --show-error --silent --location --retry 3 --connect-timeout 20 "$1" -o "$tmp"
}

tool=codebuddy
export CB_ROOT="${CB_ROOT:-/taijifs_zwfy8/share-305477973/hy_test/codebuddy_cli}"
[[ "$CB_ROOT" == /* ]] || fail '共享目录必须为绝对路径。'
export CODEBUDDY_CONFIG_DIR="$CB_ROOT/config"
export DISABLE_AUTOUPDATER=1
mkdir -p -- "$CB_ROOT/bin"
if [[ "$mode" == migrate ]]; then
    migrate_data "${CB_MIGRATE_FROM:-$HOME/.codebuddy}" "$CODEBUDDY_CONFIG_DIR"
else
    [[ ! -e "$CODEBUDDY_CONFIG_DIR/.tx-hy-migration-incomplete" ]] || fail '上次迁移未完成，请先检查目标数据。'
    mkdir -p -- "$CODEBUDDY_CONFIG_DIR"
    chmod 700 -- "$CODEBUDDY_CONFIG_DIR"
fi
binary="$CB_ROOT/bin/codebuddy"
if [[ "$mode" == update || ! -x "$binary" ]]; then
    download_installer https://www.codebuddy.cn/cli/install.sh
    bash "$tmp"
    # 指定官方安装位置，避免 command -v 命中旧共享版本/npm 包装脚本。
    src=$(readlink -f -- "$HOME/.local/bin/codebuddy")
    [[ -x "$src" ]] || fail '未找到 ~/.local/bin/codebuddy 原生安装。'
    # Linux 原生文件应为 ELF；拒绝把依赖 Node.js 的脚本当单文件复制。
    magic=$(od -An -tx1 -N4 -- "$src" | tr -d ' \n')
    [[ "$magic" == 7f454c46 ]] || fail '安装结果不是 ELF 二进制，停止复制。'
    "$src" --version
    rm -f -- "$tmp"
    tmp=$(mktemp "$CB_ROOT/bin/.codebuddy.XXXXXX")
    install -m 755 -- "$src" "$tmp"
    "$tmp" --version
    mv -fT -- "$tmp" "$binary"
    tmp=''
fi
"$binary" --version
mkdir -p "$HOME/.config/tx_hy"
env_file="$HOME/.config/tx_hy/codebuddy-env.sh"
{
    printf '# Generated by setup_codebuddy.sh; source this file in Bash.\n'
    printf 'export CB_ROOT=%q\n' "$CB_ROOT"
    cat <<'EOF'
export CODEBUDDY_CONFIG_DIR="$CB_ROOT/config"
export DISABLE_AUTOUPDATER=1
# 移到 PATH 首位并去重；局部变量不影响调用者。
_tx_hy_codebuddy_path() {
    local target="$CB_ROOT/bin" rest="${PATH-}" part result=""
    while [[ "$rest" == *:* ]]; do
        part="${rest%%:*}"
        rest="${rest#*:}"
        [[ "$part" == "$target" ]] || result+=":$part"
    done
    [[ "$rest" == "$target" ]] || result+=":$rest"
    export PATH="$target$result"
}
_tx_hy_codebuddy_path
unset -f _tx_hy_codebuddy_path
EOF
} > "$env_file"
chmod 600 "$env_file"
write_bashrc_entry "$env_file"
printf '\n配置完成。当前终端执行：\nsource %q\nhash -r\n' "$env_file"
cat <<'EOF'

# 进入项目目录后使用（以下命令不会自动执行）：
codebuddy -r                    # 选择历史会话
codebuddy -c                    # 继续最近一次对话
codebuddy                       # 新建会话
# 共享程序升级统一使用 bash setup_codebuddy.sh update。
# 若登录凭据由外部密钥环保存，更换容器后可能需要重新登录。
# 保留相同项目挂载路径，便于恢复原项目会话。
EOF
