#!/usr/bin/env bash
# Codex：共享会话数据，每个容器安装自己的命令入口。
# 首次从 ~/.codex 迁移：bash setup_codex.sh migrate
# 已迁移/更换容器/全新安装：bash setup_codex.sh setup
# 手动升级：bash setup_codex.sh update
# 可覆盖目标：CODEX_SHARED_HOME=/共享路径/codex_home bash setup_codex.sh setup
# 可覆盖迁移源：CODEX_MIGRATE_FROM=/旧路径 bash setup_codex.sh migrate
# 官方说明：https://learn.chatgpt.com/docs/config-file/environment-variables
# Linux + Bash；用 bash 执行本脚本，不要 source 本脚本。
# 依赖 curl、CA 证书和 GNU coreutils；无需激活 Conda，也不改动训练环境。
# 共享目录需提前挂载且允许执行；不同 CPU 架构不要共用同一份二进制。
# 迁移/升级前退出所有使用该共享目录的 CLI（包括其他容器）。
# 目录含登录信息，请仅供本人使用；不要同时从多台主机写同一份状态数据库。
# 代理沿用当前 shell 的 http_proxy/https_proxy/no_proxy，不写入 bashrc。
# 非交互任务请显式 source 下文生成的 env 文件，不依赖 /etc/profile。
[[ "${BASH_SOURCE[0]}" == "$0" ]] || { echo '请用 bash 执行，不要 source。' >&2; return 1; }
set -euo pipefail
umask 077
mode="${1:-setup}"
case "$mode" in setup|migrate|update) ;; *) echo "用法：bash $0 [setup|migrate|update]" >&2; exit 2;; esac
fail() { echo "错误：$*" >&2; exit 1; }
[[ $(uname -s) == Linux ]] || fail '本脚本用于 Linux 容器。'
# migrate 只允许目标不存在；失败后保留部分副本，人工检查后再处理，绝不自动覆盖。
migrate_data() {
    local src="$1" dst="$2"
    [[ -d "$src" ]] || fail "源目录不存在：$src"
    [[ ! -e "$dst" && ! -L "$dst" ]] || fail "目标已存在，请检查后使用 setup：$dst"
    src=$(realpath -e -- "$src")
    dst=$(realpath -m -- "$dst")
    case "$dst/" in "$src/"*) fail '迁移目标不能位于源目录内。';; esac
    mkdir -p -- "$(dirname -- "$dst")"
    mkdir -m 700 -- "$dst"
    touch "$dst/.tx-hy-migration-incomplete"
    cp -a -- "$src/." "$dst/"
    rm -- "$dst/.tx-hy-migration-incomplete"
    chmod 700 -- "$dst"
}
# 只追加一次入口；后续更新独立 env 文件，避免不断追加 export。
# 若之前已有旧 export，保留原文；本入口放在末尾，以当前配置为准。
write_bashrc_entry() {
    local env_file="$1" line
    printf -v line '[ -r %q ] && source %q # tx_hy-%s-env' "$env_file" "$env_file" "$tool"
    touch "$HOME/.bashrc"
    if ! grep -Fqx -- "$line" "$HOME/.bashrc"; then
        cp -p -- "$HOME/.bashrc" "$HOME/.bashrc.bak.$(date +%Y%m%d%H%M%S).$$"
        printf '\n%s\n' "$line" >> "$HOME/.bashrc"
    fi
}
tmp=''
trap '[[ -z "$tmp" ]] || rm -f -- "$tmp"' EXIT
# 先完整下载再执行，避免下载中断时运行不完整安装脚本。
download_installer() {
    command -v curl >/dev/null || fail '请先安装 curl 和 ca-certificates。'
    tmp=$(mktemp)
    curl --fail --show-error --silent --location --retry 3 --connect-timeout 20 "$1" -o "$tmp"
}

tool=codex
shared="${CODEX_SHARED_HOME:-/taijifs_zwfy8/share-305477973/hy_test/codex_home}"
[[ "$shared" == /* ]] || fail '共享目录必须为绝对路径。'
if [[ "$mode" == migrate ]]; then
    migrate_data "${CODEX_MIGRATE_FROM:-$HOME/.codex}" "$shared"
else
    [[ ! -e "$shared/.tx-hy-migration-incomplete" ]] || fail '上次迁移未完成，请先检查目标数据。'
    mkdir -p -- "$shared"
    chmod 700 -- "$shared"
fi
export CODEX_HOME="$shared"
# 官方安装器可将配套组件存于 CODEX_HOME；不擅自只复制一个可执行文件。
export CODEX_INSTALL_DIR="$HOME/.local/bin"
export CODEX_NON_INTERACTIVE=1
if [[ "$mode" == update || ! -x "$CODEX_INSTALL_DIR/codex" ]]; then
    download_installer https://chatgpt.com/codex/install.sh
    sh "$tmp"
fi
[[ -x "$CODEX_INSTALL_DIR/codex" ]] || fail '未找到安装后的 Codex 命令。'
"$CODEX_INSTALL_DIR/codex" --version
mkdir -p "$HOME/.config/tx_hy"
env_file="$HOME/.config/tx_hy/codex-env.sh"
{
    printf '# Generated by setup_codex.sh; source this file in Bash.\n'
    printf 'export CODEX_HOME=%q\n' "$shared"
    cat <<'EOF'
# 移到 PATH 首位并去重；局部变量不影响调用者。
_tx_hy_codex_path() {
    local target="$HOME/.local/bin" rest="${PATH-}" part result=""
    while [[ "$rest" == *:* ]]; do
        part="${rest%%:*}"
        rest="${rest#*:}"
        [[ "$part" == "$target" ]] || result+=":$part"
    done
    [[ "$rest" == "$target" ]] || result+=":$rest"
    export PATH="$target$result"
}
_tx_hy_codex_path
unset -f _tx_hy_codex_path
EOF
} > "$env_file"
chmod 600 "$env_file"
write_bashrc_entry "$env_file"
printf '\n配置完成。当前终端执行：\nsource %q\nhash -r\n' "$env_file"
cat <<'EOF'

# 进入项目目录后使用（以下命令不会自动执行）：
codex resume --all               # 列出不同工作目录下的会话
codex resume --last --all        # 恢复所有目录中最近一次会话
codex                           # 新建会话

# 如需沿用原来的权限设置，可手动执行；danger-full-access 关闭执行沙箱：
# codex resume --all --sandbox danger-full-access --ask-for-approval on-request
# codex --sandbox danger-full-access --ask-for-approval on-request
# CLI 参数以已安装版本的 codex --help / codex resume --help 为准。
# 项目文件也要挂载到新容器；保存会话不会自动保存项目工作目录。
# 不自动修改 sqlite_home/CODEX_SQLITE_HOME；如已有自定义数据库路径，需另行迁移。
EOF
